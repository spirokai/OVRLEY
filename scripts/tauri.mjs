import { spawn } from 'node:child_process'
import { existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
// Machine-specific build settings; shell variables take precedence.
if (existsSync(join(rootDir, '.env.local'))) process.loadEnvFile(join(rootDir, '.env.local'))
const tauriScript = join(rootDir, 'node_modules', '@tauri-apps', 'cli', 'tauri.js')

const args = process.argv.slice(2)
const tauriArgs =
  args[0] === 'dev'
    ? [
        ...args,
        '--config',
        // Generated by `pnpm prepare:packaging`, which dev does not run.
        JSON.stringify({ bundle: { resources: { 'target/packaging/THIRD_PARTY_NOTICES.txt': null } } }),
      ]
    : args
const shouldBuildPortable =
  args[0] === 'build' &&
  !args.includes('--help') &&
  !args.includes('-h') &&
  !args.includes('--bundles') &&
  !args.includes('-b') &&
  !args.includes('--no-bundle')

if (!shouldBuildPortable) {
  process.exitCode = await run(process.execPath, [tauriScript, ...tauriArgs])
} else {
  const tauriBuildArgs = defaultTauriBuildArgs(args)
  const buildCode = await run(process.execPath, [tauriScript, ...tauriBuildArgs])
  if (buildCode !== 0 || process.platform === 'linux') {
    process.exitCode = buildCode
  } else {
    const profile = args.includes('--debug') || args.includes('-d') ? 'debug' : 'release'
    process.exitCode = await run(process.execPath, [join(rootDir, 'packaging', 'portable.mjs'), '--profile', profile])
  }
}

function defaultTauriBuildArgs(args) {
  if (process.platform === 'darwin') {
    return [...args, '--bundles', 'app']
  }
  if (process.platform === 'linux') {
    return [...args, '--bundles', 'deb']
  }
  return [...args, '--no-bundle']
}

function run(command, commandArgs) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, commandArgs, {
      cwd: rootDir,
      stdio: 'inherit',
      env: process.env,
    })
    child.on('error', reject)
    child.on('exit', (code) => resolvePromise(code ?? 1))
  })
}
